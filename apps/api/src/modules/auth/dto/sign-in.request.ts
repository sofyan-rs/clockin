import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { DevicePlatform } from '@prisma/client';
import { Type } from 'class-transformer';
import {
  IsEmail,
  IsEnum,
  IsObject,
  IsOptional,
  IsString,
  IsUUID,
  MaxLength,
  MinLength,
  ValidateNested,
} from 'class-validator';

export class DeviceInfo {
  @ApiProperty({ description: 'Install id generated by the app (UUID)' })
  @IsUUID()
  id!: string;

  @ApiProperty({ enum: DevicePlatform, enumName: 'DevicePlatform' })
  @IsEnum(DevicePlatform)
  platform!: DevicePlatform;

  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(100) model?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(50) osVersion?: string;
  @ApiPropertyOptional() @IsOptional() @IsString() @MaxLength(50) appVersion?: string;
}

export class MobileSignInRequest {
  @ApiProperty({ description: 'Work email or Employee ID (FR-M1)' })
  @IsString()
  @MinLength(1)
  @MaxLength(254)
  login!: string;

  @ApiProperty() @IsString() @MinLength(1) @MaxLength(200) password!: string;

  @ApiProperty({ type: DeviceInfo })
  @IsObject() // ValidateNested alone lets a missing object through
  @ValidateNested()
  @Type(() => DeviceInfo)
  device!: DeviceInfo;
}

export class AdminSignInRequest {
  @ApiProperty() @IsEmail() @MaxLength(254) email!: string;
  @ApiProperty() @IsString() @MinLength(1) @MaxLength(200) password!: string;
}

export class RefreshRequest {
  @ApiProperty() @IsString() @MinLength(1) @MaxLength(200) refreshToken!: string;
}
